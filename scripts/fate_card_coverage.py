#!/usr/bin/env python3
"""Check the six Fate replacements and their source-to-executed-test coverage."""
import task_registry
import argparse
import json
from pathlib import Path

from card_coverage import test_link, verify_results

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs/rules/T32-CARD-COVERAGE.md"


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def verify_card(card, source, metadata, text):
    assert source["effectsVerified"] and source["verification"] == "second_edition_front_reviewed"
    assert card["eventImplemented"] and card["combatImplemented"]
    assert card["setup"] == source["setup"] and card["setup"]["operation"] == "replace"
    assert card["combatInitiatives"] == source["initiative"] == text["initiative"]
    assert len(card["combatPrograms"]) == len(card["combatInitiatives"]) == 1
    assert card["programId"] and card["tests"] and text["event"] and text["combat"]
    assert text["combatTitle"] == source["combatTitle"]
    for section in ("eventRules", "combatRules", "verificationCases"):
        assert [item["sourceText"] for item in card[section]] == source[section]
        assert all(item["tests"] and set(item["tests"]) <= set(card["tests"]) for item in card[section])
    for field in ("title", "side", "eventType"):
        assert metadata[field] == source[field], f"Incorrect {field}: {card['id']}"
    assert metadata["deck"] == source["deck"].lower()
    assert metadata["replaces"] == source["setup"]["replaces"]


def verified_cards():
    manifest = read("content/fate-card-implementation-manifest.json")
    cards = {card["id"]: card for card in manifest["cards"]}
    sources = {card["id"]: card for card in read(manifest["source"])["cards"]}
    metadata = {card["id"]: card for card in read("content/fate-cards.json")}
    texts = {card["id"]: card for card in read("content/fate-card-text.json")}
    assert len(cards) == len(manifest["cards"]) == 6
    assert set(cards) == set(sources) == set(metadata) == set(texts)
    pack = next(task for task in task_registry.records() if task["id"] == "T32-CARDS")
    assert len(pack["content_ids"]) == len(set(pack["content_ids"])) == 6
    assert set(pack["content_ids"]) == set(cards)
    assert len({card["setup"]["replaces"] for card in cards.values()}) == 6
    # The client receives these through the pinned public content package and checks its copies there.
    for name in ("fate-cards.json", "fate-card-text.json"):
        assert name in read("content/unity-public-content.json")["files"]
    for card_id, card in cards.items():
        verify_card(card, sources[card_id], metadata[card_id], texts[card_id])
    return cards, sources


def report(cards, sources):
    lines = ["# T32 — manifest of six Fate cards", "",
             "Generated by `python3 scripts/fate_card_coverage.py`; `--check` verifies freshness.", "",
             "[Sources](../sources/fate-index.json), [rules](T32-FATE-CARDS.md), "
             "[implementation manifest](../../content/fate-card-implementation-manifest.json). "
             "Six replacements preserve deck sizes and disable the corresponding base-game/Kings versions.", "",
             "`FateCardManifestTests` compares the manifest with the actual C# catalog. "
             "`--results <TRX>` requires passing results for all assigned methods. "
             "Acceptance status is defined in tasks.json; generating the report alone does not complete the task.", "",
             "| Card | Slot | Event / Combat (initiative) | Behavioral tests |",
             "| --- | --- | --- | --- |"]
    for card_id, card in cards.items():
        source = sources[card_id]
        combat = ", ".join(f"`{program}` ({initiative})" for program, initiative in
                           zip(card["combatPrograms"], card["combatInitiatives"]))
        tests = "<br>".join(test_link(name) for name in card["tests"])
        lines.append(f"| `{card_id}` — {source['title']} | `{source['setup']['replaces']}` | "
                     f"`{card['programId']}` / {combat} | {tests} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--results", type=Path)
    args = parser.parse_args()
    cards, sources = verified_cards()
    content = report(cards, sources)
    if args.check:
        assert REPORT.exists() and REPORT.read_text(encoding="utf-8") == content, "Regenerate Fate card coverage report"
    else:
        REPORT.write_text(content, encoding="utf-8")
    if args.results:
        verify_results(args.results, cards)
    print("PASS: six Fate cards, both uses, six distinct replacements, source clauses, public client content")


if __name__ == "__main__":
    main()
