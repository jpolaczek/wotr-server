#!/usr/bin/env python3
"""Verify both Fate Gimli fronts, exact source clauses and executed behavior tests."""
import task_registry
import argparse
from pathlib import Path

from card_coverage import test_link, verify_results
from fate_card_coverage import read

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs/rules/T32-GIMLI-COVERAGE.md"


def verified_cards():
    manifest = read("content/fate-character-implementation-manifest.json")
    cards = {card["id"]: card for card in manifest["cards"]}
    sources = {card["id"]: card for card in read(manifest["source"])["characters"]}
    metadata = {card["id"]: card for card in read("content/fate-characters.json")}
    assert len(cards) == len(manifest["cards"]) == 2
    assert set(cards) == set(sources) == set(metadata)
    task = next(t for t in task_registry.records() if t["id"] == "T32-GIMLI")
    assert len(task["content_ids"]) == 2 and set(task["content_ids"]) == set(cards)
    # The client receives it through the pinned public content package and checks its copy there.
    assert "fate-characters.json" in read("content/unity-public-content.json")["files"]
    for card_id, card in cards.items():
        source, definition = sources[card_id], metadata[card_id]
        assert source["effectsVerified"] and source["verification"] == "second_edition_front_reviewed"
        assert card["setup"] == source["setup"]
        for field in ("identity", "title", "side", "level", "leadership", "nationIcon", "extraActionDice"):
            assert definition[field] == source[field], (card_id, field)
        assert definition["role"] == "Companion" and definition["initial"]
        assert [item["id"] for item in card["abilities"]] == definition["abilities"]
        for field in ("entryTests", "exitTests"):
            assert card[field] and set(card[field]) <= set(card["tests"])
        for field, source_field in (("sourceAbilities", "abilities"), ("verificationCases", "verificationCases")):
            assert [item["sourceText"] for item in card[field]] == source[source_field]
        for field in ("abilities", "sourceAbilities", "verificationCases"):
            assert all(item["tests"] and set(item["tests"]) <= set(card["tests"]) for item in card[field])
    return cards, sources


def report(cards, sources):
    lines = ["# T32 — manifest of both Gimli versions", "",
             "Generated by `python3 scripts/fate_character_coverage.py`; `--check` verifies freshness, "
             "and `--results <TRX>` requires the assigned methods to pass. "
             "`FateGimliManifestTests` checks the actual C# catalog.", "",
             "[Rules](T32-FATE-GIMLI.md), [sources](../sources/fate-index.json), "
             "[manifest](../../content/fate-character-implementation-manifest.json). "
             "Acceptance status remains in tasks.json. Council UI is the separate UI-09 task.", "",
             "| Card front | Replacement | Abilities / source cases | Tests |", "| --- | --- | --- | --- |"]
    for card_id, card in cards.items():
        source = sources[card_id]
        tests = "<br>".join(test_link(name) for name in card["tests"])
        lines.append(f"| `{card_id}` — {source['subtitle']} | `{card['setup']['replaces']}` | "
                     f"{len(card['sourceAbilities'])} / {len(card['verificationCases'])} | {tests} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--results", type=Path)
    args = parser.parse_args()
    cards, sources = verified_cards()
    content = report(cards, sources)
    if args.check:
        assert REPORT.exists() and REPORT.read_text(encoding="utf-8") == content, "Regenerate Fate Gimli coverage"
    else:
        REPORT.write_text(content, encoding="utf-8")
    if args.results:
        verify_results(args.results, cards)
    print("PASS: two Fate Gimli fronts, six runtime abilities, seven source clauses, seven source cases, client metadata")


if __name__ == "__main__":
    main()
