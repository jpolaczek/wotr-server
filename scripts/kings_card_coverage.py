#!/usr/bin/env python3
"""Verify all Kings card implementations, explicit replacements and executed tests."""
import task_registry
import argparse
import json
from pathlib import Path

from card_coverage import test_link, verify_results

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs/rules/T30-CARD-COVERAGE.md"
FATE_EXCLUSIONS = {"kings.fp.strategy.19", "kings.fp.strategy.22"}


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def verify_card(card, source, metadata):
    assert source["implemented"] and source["effectsVerified"]
    assert card["kind"] == source["kind"] == "Event"
    assert card["eventImplemented"] and card["combatImplemented"]
    assert card["setup"] == source["setup"], f"Incorrect replacement: {card['id']}"
    assert card["combatInitiatives"] == source["initiative"]
    assert card["programId"] and card["tests"]
    assert len(card["combatPrograms"]) == len(card["combatInitiatives"]) == 1
    for section in ("eventRules", "combatRules", "verificationCases"):
        assert [item["sourceText"] for item in card[section]] == source[section]
        assert all(item["tests"] and set(item["tests"]) <= set(card["tests"]) for item in card[section])
    for field in ("title", "side", "eventType"):
        assert metadata[field] == source[field], f"Incorrect {field}: {card['id']}"
    assert metadata["deck"] == source["deck"].lower()
    assert metadata["replaces"] == (source["setup"]["replaces"] or "")
    assert metadata["excludedWithFate"] == (card["id"] in FATE_EXCLUSIONS)


def verified_cards():
    manifest = read("content/kings-card-implementation-manifest.json")
    cards = {card["id"]: card for card in manifest["cards"]}
    assert len(cards) == len(manifest["cards"]) == 19, "Expected 19 distinct Kings cards"
    sources = {card["id"]: card for card in read(manifest["source"])["cards"]}
    metadata = {card["id"]: card for card in read("content/kings-cards.json")}
    assert set(cards) == set(sources) == set(metadata), "Incomplete source or runtime coverage"
    # The client receives both through the pinned public content package and checks its copies there.
    assert {"kings-cards.json", "kings-card-text.json"} <= set(read("content/unity-public-content.json")["files"])
    packs = [task for task in task_registry.records() if task["id"].startswith("T30-CARDS-")]
    assert len(packs) == 4 and sorted(len(pack["content_ids"]) for pack in packs) == [1, 6, 6, 6]
    assert all(pack["status"] == "done" for pack in packs), "Unfinished Kings pack"
    covered = [card for pack in packs for card in pack["content_ids"]]
    assert len(covered) == len(set(covered)) == 19 and set(covered) == set(cards)
    assert sum(card["setup"]["operation"] == "replace" for card in cards.values()) == 11
    assert sum(card["setup"]["operation"] == "add" for card in cards.values()) == 8
    assert {card["id"] for card in cards.values() if "FateOfErebor" in card["setup"].get("excludedWith", [])} == FATE_EXCLUSIONS
    for card_id, card in cards.items():
        verify_card(card, sources[card_id], metadata[card_id])
    return sources, cards, packs


def report(sources, cards, packs):
    lines = ["# T30 — manifest of 19 Kings cards", "",
             "Generated by `python3 scripts/kings_card_coverage.py`; `--check` verifies freshness.", "",
             "[Sources](../sources/kings-card-index.json), [implementation manifest](../../content/kings-card-implementation-manifest.json) "
             "and [acceptance](T30-ACCEPTANCE.md). 11 replacements and eight new cards, each with Event and Combat uses. "
             "Base game+Kings: 104 cards; with Lords: 116. Fate disables exactly the two specified replacements.", "",
             "`KingsCardManifestTests` compares programs with the actual C# catalog. "
             "`--results <TRX>` requires passing results for all referenced methods; the report does not replace tests.", ""]
    for pack in sorted(packs, key=lambda p: p["id"]):
        number = pack["id"].rsplit("-", 1)[1]
        lines.extend([f"## {pack['id']}", "", f"[Logic and sources](T30-KINGS-{number}.md).", "",
                      "| Card | Setup | Event / Combat (initiative) | Behavioral tests |",
                      "| --- | --- | --- | --- |"])
        for card_id in pack["content_ids"]:
            card, source = cards[card_id], sources[card_id]
            setup = f"Replaces `{card['setup']['replaces']}`" if card["setup"]["operation"] == "replace" else "New card"
            if card_id in FATE_EXCLUSIONS:
                setup += "; disabled with Fate"
            combat = ", ".join(f"`{program}` ({initiative})" for program, initiative in
                               zip(card["combatPrograms"], card["combatInitiatives"]))
            tests = "<br>".join(test_link(name) for name in card["tests"])
            lines.append(f"| `{card_id}` — {source['title']} | {setup} | `{card['programId']}` / {combat} | {tests} |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--results", type=Path)
    args = parser.parse_args()
    sources, cards, packs = verified_cards()
    content = report(sources, cards, packs)
    if args.check:
        assert REPORT.exists() and REPORT.read_text(encoding="utf-8") == content, "Regenerate Kings card coverage report"
    else:
        REPORT.write_text(content, encoding="utf-8")
    if args.results:
        verify_results(args.results, cards)
    print("PASS: 19 Kings cards, 11 replacements + 8 additions, two Fate exclusions, four complete packs")


if __name__ == "__main__":
    main()
