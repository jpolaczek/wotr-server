#!/usr/bin/env python3
"""Local WoTR task registry. Python standard library, no network or dependencies."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
from datetime import datetime, timezone

import crossrepo
import task_registry

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "docs/tasks/tasks.json"
INDEX = ROOT / "docs/tasks/INDEX.md"
STAGES = {"A": "Foundations", "B": "First playable sequence",
          "C": "Complete base game", "D": "Expansions and variants",
          "E": "Correspondence play, quality and release"}
SECTIONS = ["Goal", "Context and dependencies", "Logic and scope",
            "Acceptance criteria", "Verification", "Documentation and handoff"]
PEERS = crossrepo.peers(ROOT)


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def atomic_write(path, text):
    temp = path.with_name(path.name + ".tmp")
    with temp.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temp, path)


def gaps_by_id():
    return {g["id"]: g for g in read_json(ROOT / "docs/sources/gaps.json")["gaps"]}


def blockers(task, tasks, gaps):
    result = [dep for dep in task["depends_on"]
              if dep not in tasks or tasks[dep]["status"] != "done"]
    result += [gate for gate in task["source_gates"]
               if gate not in gaps or gaps[gate]["status"] != "resolved"]
    if task.get("content_count") and len(task.get("content_ids", [])) != task["content_count"]:
        result.append("incomplete content_ids")
    return result


def ordered(data):
    return sorted(data["tasks"], key=lambda t: (t["stage"], t["priority"], t["id"]))


def display_status(task, tasks, gaps):
    if task["status"] == "planned" and not blockers(task, tasks, gaps):
        return "ready"
    return task["status"]


def index_text(data):
    tasks = {t["id"]: t for t in task_registry.records(data)}
    gaps = gaps_by_id()
    done = sum(t["status"] == "done" for t in tasks.values())
    lines = ["# Task registry", "",
             "Generated by `python3 scripts/tasks.py render`. Do not edit task states here.", "",
             f"Active tasks: **{len(data['tasks'])}**. Completion identifiers: **{done}**. "
             "`ready` means dependencies and gates are satisfied; it does not authorize a new stage.", "",
             "[Stages and order](../ROADMAP.md) · [Workflow](../WORKFLOW.md) · "
             "[Active task states](tasks.json) · [Completion identifiers](completions.json)", ""]
    for stage, title in STAGES.items():
        if not any(t["stage"] == stage for t in data["tasks"]):
            continue
        lines += [f"## {stage} — {title}", "",
                  "| ID | Task | State | Remaining start conditions |",
                  "| --- | --- | --- | --- |"]
        for task in ordered(data):
            if task["stage"] != stage:
                continue
            waiting = blockers(task, tasks, gaps)
            short = ", ".join(waiting[:3])
            if len(waiting) > 3:
                short += f" (+{len(waiting) - 3})"
            title_safe = task["title"].replace("|", "\\|")
            status = display_status(task, tasks, gaps)
            lines.append(f"| [{task['id']}]({task['id']}.md) | {title_safe} | `{status}` | {short or '—'} |")
        lines.append("")
    lines += ["## Current work", ""]
    active = [t for t in ordered(data) if t["status"] in ("in_progress", "blocked")]
    for task in active:
        lines.append(f"- **{task['id']}**: `{task['status']}`, {task['assignee'] or 'unassigned'}; "
                     f"start {task['started_at'] or '—'}. {task.get('blocked_reason') or ''}".rstrip())
    if not active:
        lines.append("No active or blocked tasks.")
    return "\n".join(lines).rstrip() + "\n"


def save(data):
    atomic_write(REGISTRY, json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    atomic_write(INDEX, index_text(data))


def relative_file(value):
    # `wotr-client:<path>` names a file of the pinned peer repository (DIST-03).
    pinned = crossrepo.reference(PEERS, value)
    if pinned is not None:
        return pinned
    path = (ROOT / value).resolve()
    try:
        path.relative_to(ROOT)
    except ValueError:
        return False
    return path.is_file()


def local_only_files():
    """D17: files kept outside git (docs/sources/LOCAL-ONLY.json), by resolved path, with their SHA-256."""
    listing = ROOT / "docs/sources/LOCAL-ONLY.json"
    if not listing.is_file():
        return {}
    return {(ROOT / item["path"]).resolve(): item["sha256"] for item in json.loads(listing.read_text())["files"]}


def validate(data):
    errors = []
    entries = data["tasks"]
    all_entries = task_registry.records(data)
    tasks = {t["id"]: t for t in all_entries}
    if len(tasks) != len(all_entries):
        errors.append("Duplicate task identifier")
    gaps_list = read_json(ROOT / "docs/sources/gaps.json")["gaps"]
    gaps = {g["id"]: g for g in gaps_list}
    sources_list = read_json(ROOT / "docs/sources/manifest.json")["sources"]
    sources = {s["id"]: s for s in sources_list}
    rules_list = read_json(ROOT / "docs/rules/catalog.json")["rules"]
    rules = {r["id"]: r for r in rules_list}
    for label, items, lookup in [("gates", gaps_list, gaps), ("sources", sources_list, sources),
                                 ("rules", rules_list, rules)]:
        if len(items) != len(lookup):
            errors.append(f"Duplicate IDs: {label}")
    requirements = set(re.findall(r"\| (R\d+) \|", (ROOT / "docs/REQUIREMENTS.md").read_text()))
    covered = set()
    for completed in task_registry.completed_records():
        if completed.get("stage") not in STAGES:
            errors.append(f"Invalid completed stage: {completed['id']}")
        for req in completed.get("requirements", []):
            if req not in requirements:
                errors.append(f"Unknown completed requirement: {req}")
            covered.add(req)
    content_seen = {}
    content_totals = {}
    for task in entries:
        ident = task["id"]
        def error(message):
            errors.append(f"{ident}: {message}")
        if task["stage"] not in STAGES:
            error("unknown stage")
        if task["status"] not in ("planned", "in_progress", "blocked", "done"):
            error("unknown stored state")
        for key in ("depends_on", "source_gates", "requirements", "rules", "read_before", "update_docs"):
            if len(task[key]) != len(set(task[key])):
                error(f"duplicate values in {key}")
        for dep in task["depends_on"]:
            if dep not in tasks or dep == ident:
                error(f"invalid dependency {dep}")
            elif tasks[dep]["stage"] > task["stage"]:
                error(f"dependency on a later stage {dep}")
        for gate in task["source_gates"]:
            if gate not in gaps:
                error(f"unknown gate {gate}")
        for req in task["requirements"]:
            if req not in requirements:
                error(f"unknown requirement {req}")
            covered.add(req)
        for rule in task["rules"]:
            if rule not in rules:
                error(f"unknown rule {rule}")
        for path in [task["spec"]] + task["read_before"] + task["update_docs"] + task["documentation"]:
            if not relative_file(path):
                error(f"missing file {path}")
        spec = ROOT / task["spec"]
        if spec.is_file():
            body = spec.read_text()
            for section in SECTIONS:
                if f"## {section}\n" not in body:
                    error(f"missing section {section}")
        history = task["history"]
        times = []
        for event in history:
            try:
                times.append(datetime.fromisoformat(event["at"].replace("Z", "+00:00")))
            except (ValueError, KeyError):
                error("invalid history timestamp")
            if not event.get("note", "").strip():
                error("empty history note")
        if times != sorted(times):
            error("history is not chronological")
        if task["status"] != "planned":
            if not task["started_at"] or not task["assignee"] or not history:
                error("missing start metadata")
            elif history[0]["event"] != "start" or history[0]["at"] != task["started_at"]:
                error("history does not begin with the recorded start")
        if task["status"] == "blocked" and not task["blocked_reason"]:
            error("missing blocking reason")
        if task["status"] == "done":
            if not task["finished_at"] or not task["checks"] or not task["documentation"]:
                error("missing completion evidence")
            if not history or history[-1]["event"] != "finish" or history[-1]["at"] != task["finished_at"]:
                error("missing matching finish entry")
            if blockers(task, tasks, gaps):
                error("done despite unsatisfied conditions")
    for req in sorted(requirements - covered):
        errors.append(f"Requirement without a task: {req}")
    for task in all_entries:
        if task.get("content_count"):
            count, group, ids = task["content_count"], task["content_group"], task["content_ids"]
            if count < 1 or count > 6 or (ids and len(ids) != count):
                errors.append(f"{task['id']}: invalid card pack size")
            content_totals[group] = content_totals.get(group, 0) + count
            for content_id in ids:
                if content_id in content_seen:
                    errors.append(f"{task['id']}: card {content_id} also appears in {content_seen[content_id]}")
                content_seen[content_id] = task["id"]
    expected_counts = {"base": 96, "lords": 14, "kings": 19, "fate-event": 6, "fate-character": 2}
    if content_totals != expected_counts:
        errors.append(f"Incomplete content packs: {content_totals}")
    visiting, visited = set(), set()
    def walk(ident):
        if ident in visiting:
            errors.append(f"Dependency cycle at {ident}")
            return
        if ident in visited or ident not in tasks:
            return
        visiting.add(ident)
        for dep in tasks[ident]["depends_on"]:
            walk(dep)
        visiting.remove(ident)
        visited.add(ident)
    for ident in tasks:
        walk(ident)
    for gap in gaps.values():
        if gap["status"] not in ("open", "resolved"):
            errors.append(f"Unknown gate state {gap['id']}")
        if gap["status"] == "resolved" and not gap.get("resolution"):
            errors.append(f"Missing resolution evidence for {gap['id']}")
        for task_id in [gap["owner_task"]] + gap["affected"]:
            if task_id not in tasks:
                errors.append(f"Gate {gap['id']}: unknown task {task_id}")
        if gap["status"] == "open" and gap["owner_task"] in tasks and tasks[gap["owner_task"]]["status"] == "done":
            errors.append(f"Open gate {gap['id']} requires an active follow-up task instead of a completed owner")
    for rule in rules.values():
        if rule["source"] not in sources or not relative_file(rule["document"]):
            errors.append(f"Invalid rule source/document {rule['id']}")
    local_only = local_only_files()
    for source in sources.values():
        if source["kind"] == "local_pdf":
            path = ROOT / source["path"]
            # D17: Ares Games publications stay outside git; a local copy must still be the pinned file.
            if not path.is_file() and path.resolve() in local_only:
                continue
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != source["sha256"]:
                errors.append(f"Missing or modified source checksum {source['id']}")
    for path, digest in local_only.items():
        if path.is_file() and hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            errors.append(f"Local-only file differs from docs/sources/LOCAL-ONLY.json: {path.relative_to(ROOT)}")
    markdown = list((ROOT / "docs").rglob("*.md")) + [ROOT / "README.md", ROOT / "AGENTS.md"]
    for path in markdown:
        body = path.read_text(encoding="utf-8")
        for target in re.findall(r"\[[^\]]*\]\(([^\s)]+)\)", body):
            pinned = crossrepo.link_error(PEERS, target)
            if pinned:
                errors.append(f"{path.relative_to(ROOT)}: {pinned}")
            if pinned is not None or re.match(r"[a-zA-Z][\w+.-]*:", target) or target.startswith("#"):
                continue
            local = target.split("#", 1)[0]
            resolved = (path.parent / local).resolve()
            if not resolved.exists() and resolved not in local_only:
                errors.append(f"{path.relative_to(ROOT)}: broken link {target}")
        if any(line.rstrip() != line for line in body.splitlines()):
            errors.append(f"{path.relative_to(ROOT)}: trailing whitespace")
    if not INDEX.is_file() or INDEX.read_text() != index_text(data):
        errors.append("Index is stale; run tasks.py render")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest="command", required=True)
    for name in ("list", "ready"):
        command = subs.add_parser(name)
        command.add_argument("--stage", choices=STAGES)
    subs.add_parser("validate")
    subs.add_parser("render")
    pinning = subs.add_parser("pin-repo", help="Pin the other repository commit and update its links.")
    pinning.add_argument("alias")
    pinning.add_argument("--checkout", type=Path, required=True)
    pinning.add_argument("--repository", required=True)
    pinning.add_argument("--revision", default="HEAD")
    for name in ("show", "start", "note", "block", "finish"):
        command = subs.add_parser(name)
        command.add_argument("id")
        if name == "start":
            command.add_argument("--agent", required=True)
        if name in ("start", "note"):
            command.add_argument("--note", required=True)
        if name == "block":
            command.add_argument("--reason", required=True)
        if name == "finish":
            command.add_argument("--summary", required=True)
            command.add_argument("--check", action="append", required=True)
            command.add_argument("--docs", action="append", required=True)
    args = parser.parse_args()
    data = read_json(REGISTRY)
    tasks = {t["id"]: t for t in task_registry.records(data)}
    gaps = gaps_by_id()
    if args.command == "validate":
        errors = validate(data)
        if errors:
            print("\n".join("ERROR: " + e for e in errors))
            return 1
        print(f"PASS: {len(data['tasks'])} active tasks and {len(task_registry.completed_records())} completion identifiers; graph, gates, requirements, rules, links, history, index and source SHA-256.")
        return 0
    if args.command == "pin-repo":
        markdown = list((ROOT / "docs").rglob("*.md")) + [ROOT / "README.md", ROOT / "AGENTS.md"]
        old, new, changed = crossrepo.pin(ROOT, args.alias, args.repository, args.checkout.resolve(),
                                          args.revision, markdown)
        print(f"{args.alias}: {old or '-'} -> {new}; updated links in {len(changed)} files.")
        return 0
    if args.command == "render":
        atomic_write(INDEX, index_text(data))
        print("Updated docs/tasks/INDEX.md")
        return 0
    if args.command in ("list", "ready"):
        found = 0
        for task in ordered(data):
            status = display_status(task, tasks, gaps)
            if args.stage and task["stage"] != args.stage:
                continue
            if args.command == "ready" and status != "ready":
                continue
            print(f"{task['id']:20} {status:12} {task['title']}")
            found += 1
        if not found:
            print("No tasks match the filter; use show to inspect dependencies and gates.")
        return 0
    task = tasks.get(args.id)
    if task is None or args.id not in {t["id"] for t in data["tasks"]}:
        parser.error("Unknown active task ID; completed identifiers are in completions.json")
    if args.command == "show":
        print(json.dumps(task, ensure_ascii=False, indent=2))
        print("Start conditions:", ", ".join(blockers(task, tasks, gaps)) or "satisfied")
        return 0
    note = getattr(args, "note", None) or getattr(args, "reason", None) or getattr(args, "summary", None)
    if not note or not note.strip():
        parser.error("A note cannot be empty")
    timestamp = now()
    event = args.command
    if args.command == "start":
        if task["status"] not in ("planned", "blocked"):
            parser.error("Start requires planned or blocked")
        waiting = blockers(task, tasks, gaps)
        if waiting:
            parser.error("Unsatisfied conditions: " + ", ".join(waiting))
        if not args.agent.strip():
            parser.error("Assignee cannot be empty")
        if any(t["status"] == "in_progress" and t["assignee"] == args.agent for t in tasks.values()):
            parser.error("Assignee already has an active task; finish or block it first")
        if task["status"] == "blocked":
            event = "resume"
        task.update(status="in_progress", assignee=args.agent, blocked_reason=None)
        task["started_at"] = task["started_at"] or timestamp
        marker = "START"
    elif args.command == "note":
        if task["status"] not in ("in_progress", "blocked"):
            parser.error("A note requires an active or blocked task")
        marker = "CHECKPOINT"
    elif args.command == "block":
        if task["status"] != "in_progress":
            parser.error("Only a started task can be blocked")
        task.update(status="blocked", blocked_reason=note)
        marker = "BLOCKED"
    else:
        if task["status"] != "in_progress":
            parser.error("Completion requires in_progress")
        if blockers(task, tasks, gaps):
            parser.error("Cannot finish with unsatisfied conditions")
        owned_gaps = [g["id"] for g in gaps.values() if g["owner_task"] == task["id"] and g["status"] == "open"]
        if owned_gaps:
            parser.error("Assign follow-up tasks for unresolved gaps before completing the audit: " + ", ".join(owned_gaps))
        if any(not check.startswith("PASS: ") or not check[6:].strip() for check in args.check):
            parser.error("Each --check requires PASS: and a description of an actually performed check")
        if any(not relative_file(path) for path in args.docs):
            parser.error("--docs must name an existing file within the repository")
        task.update(status="done", finished_at=timestamp, checks=args.check,
                    documentation=list(dict.fromkeys(args.docs)), blocked_reason=None)
        marker = "DONE"
    entry = {"at": timestamp, "event": event, "agent": task["assignee"], "note": note}
    if args.command == "finish":
        entry.update(checks=task["checks"], documentation=task["documentation"])
    task["history"].append(entry)
    save(data)
    print(f"{marker} {task['id']} — {note} ({timestamp})")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f"Registry error: {exc}", file=sys.stderr)
        sys.exit(1)
