#!/usr/bin/env python3
"""Generate base-card traceability and verify its referenced tests against a TRX run."""
import task_registry
import argparse
import json
from collections import Counter
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs/rules/T21-CARD-COVERAGE.md"


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def verified_cards():
    sources = read("docs/sources/base-card-index.json")["cards"]
    implementation = read("content/implementation-manifest.json")["cards"]
    cards = {card["id"]: card for card in implementation}
    assert len(cards) == len(implementation) == len(sources) == 96
    assert set(cards) == {card["id"] for card in sources}
    assert sorted(Counter((c["side"], c["deck"]) for c in sources).values()) == [24] * 4
    for source in sources:
        card = cards[source["id"]]
        assert card["eventImplemented"] and card["combatImplemented"]
        assert card["combatInitiatives"] == source["initiative"]
        assert card["programId"] and card["combatPrograms"] and card["tests"]
        assert len(card["combatPrograms"]) == len(card["combatInitiatives"])
    return {card["id"]: card for card in sources}, cards


def test_link(name):
    owner, method = name.split(".")
    path = f"tests/Wotr.Tests/{owner}.cs"
    assert (ROOT / path).is_file(), f"Missing test source: {path}"
    return f"[{owner}.{method}](../../{path})"


def card_row(source, card):
    programs = ", ".join(f"`{program}` ({initiative})" for program, initiative in
                         zip(card["combatPrograms"], card["combatInitiatives"]))
    tests = "<br>".join(test_link(name) for name in card["tests"])
    return (f"| `{card['id']}` — {source['title']} | `{card['programId']}` | "
            f"{source['combatTitle']}: {programs} | {tests} |")


def report(sources, cards):
    lines = ["# T21 — manifest, programs and tests for 96 cards", "",
             "Generated by `python3 scripts/card_coverage.py`; `--check` verifies freshness.", "",
             "Sources: [96 verified card fronts](../sources/base-card-index.json), "
             "[implementation manifest](../../content/implementation-manifest.json). "
             "Each row links both uses to programs and behavioral tests. "
             "The number in parentheses next to a combat program is its initiative.", "",
             "`EffectManifestTests` compares programs with the actual C# catalog and requires "
             "existing test methods that are not skipped. `--results <file.trx>` requires "
             "all executed cases of every referenced method to pass. "
             "Generating the table alone is neither a test result nor UI acceptance.", ""]
    tasks = [task for task in task_registry.records() if task["id"].startswith("T21-")]
    assigned = [card for task in tasks for card in task["content_ids"]]
    assert len(tasks) == 16 and len(assigned) == len(set(assigned)) == 96
    assert set(assigned) == set(cards)
    for task in sorted(tasks, key=lambda task: task["id"]):
        assert task["status"] == "done", f"Unfinished pack: {task['id']}"
        lines.extend([f"## {task['id']}", "",
                      f"[Rules and scope](T21-{task['id'][4:]}.md).", "",
                      "| Card | Event program | Combat programs | Tests of both uses and interactions |",
                      "| --- | --- | --- | --- |"])
        lines.extend(card_row(sources[card], cards[card]) for card in sorted(task["content_ids"]))
        lines.append("")
    return "\n".join(lines)


def verify_results(path, cards):
    tree = ET.parse(path).getroot()
    ns = {"t": tree.tag.split("}")[0][1:]}
    methods = {}
    for test in tree.findall("t:TestDefinitions/t:UnitTest", ns):
        method = test.find("t:TestMethod", ns)
        methods[test.attrib["id"]] = f"{method.attrib['className'].split('.')[-1]}.{method.attrib['name']}"
    results = tree.findall("t:Results/t:UnitTestResult", ns)
    result_ids = [result.attrib["testId"] for result in results]
    entries = {entry.attrib["testId"] for entry in tree.findall("t:TestEntries/t:TestEntry", ns)}
    assert len(result_ids) == len(set(result_ids)), "Duplicate test results in TRX"
    assert set(result_ids) == entries == set(methods), "TRX definitions, entries and results differ"
    counters = tree.find("t:ResultSummary/t:Counters", ns)
    assert counters is not None, "TRX run counters missing"
    assert all(int(counters.attrib[key]) == len(results) for key in ("total", "executed", "passed")), \
        "TRX is incomplete or contains failed/skipped tests"
    assert all(result.attrib["outcome"] == "Passed" for result in results), "TRX contains a non-passing result"
    outcomes = {}
    for result in results:
        outcomes.setdefault(methods[result.attrib["testId"]], []).append(result.attrib["outcome"])
    required = {name for card in cards.values() for name in card["tests"]}
    for name in sorted(required):
        assert name in outcomes, f"Test absent from run: {name}"
        assert all(value == "Passed" for value in outcomes[name]), f"Test did not pass: {name}"
    print(f"PASS: {len(required)} referenced methods, {sum(len(outcomes[name]) for name in required)} passed cases in {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--results", type=Path)
    args = parser.parse_args()
    sources, cards = verified_cards()
    text = report(sources, cards)
    if args.check:
        assert REPORT.exists() and REPORT.read_text(encoding="utf-8") == text, "Regenerate card coverage report"
    else:
        REPORT.write_text(text, encoding="utf-8")
    if args.results:
        verify_results(args.results, cards)
    print("PASS: 96 complete cards, four decks of 24, 16 disjoint completed packs, matching printed initiatives")


if __name__ == "__main__":
    main()
