#!/usr/bin/env python3
"""Verify implemented Lords cards against their sources, task packs and a real TRX run."""
import task_registry
import argparse
import json
from pathlib import Path

from card_coverage import test_link, verify_results

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs/rules/T27-CARD-COVERAGE.md"


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def verified_cards():
    manifest = read("content/lords-card-implementation-manifest.json")
    cards = {card["id"]: card for card in manifest["cards"]}
    assert len(cards) == len(manifest["cards"]) == 14, "Expected 14 distinct Lords cards"
    sources = {card["id"]: card for card in read(manifest["source"])["cards"]}
    assert set(cards) == set(sources), "Incomplete source coverage"
    assert all(card["implemented"] for card in sources.values())
    tasks = task_registry.records()
    packs = [task for task in tasks if task["id"].startswith("T27-CARDS-")]
    assert len(packs) == 3 and sorted(len(pack["content_ids"]) for pack in packs) == [2, 6, 6]
    covered = []
    for pack in packs:
        assert pack["status"] == "done", f"Unfinished pack: {pack['id']}"
        covered.extend(pack["content_ids"])
    assert len(covered) == len(set(covered)) == len(cards) and set(covered) == set(cards)
    for card in cards.values():
        source = sources[card["id"]]
        assert card["kind"] == source["kind"] and card["eventImplemented"]
        if card["kind"] == "SpecialEvent":
            assert not card["combatImplemented"] and not card["combatPrograms"] and not source["combatRules"]
            assert source["deck"] is None and card["automaticEntry"] and card["reactionId"]
        else:
            assert card["kind"] == "Event" and card["combatImplemented"]
        assert card["combatInitiatives"] == source["initiative"]
        for section in ("eventRules", "combatRules", "verificationCases"):
            assert [item["sourceText"] for item in card[section]] == source[section]
            assert all(item["tests"] and set(item["tests"]) <= set(card["tests"]) for item in card[section])
        assert card["tests"] and card["programId"]
        assert len(card["combatPrograms"]) == len(card["combatInitiatives"])
    return sources, cards, packs


def report(sources, cards, packs):
    lines = ["# T27 — manifest of 14 Lords cards", "",
             "Generated by `python3 scripts/lords_card_coverage.py`; `--check` verifies freshness.", "",
             "Source: [card-front index](../sources/lords-card-index.json). "
             "The [implementation manifest](../../content/lords-card-implementation-manifest.json) links "
             "each clause to a test; [acceptance](T27-ACCEPTANCE.md) describes interactions and actual results.", "",
             "13 cards have Event and Combat uses. The special We Shall Get It card enters automatically "
             "and has an optional reaction, without Combat. Decks: FP 28/26, SH 28/26, 108 total. "
             "Lords SH Character 17 replaces a base-game slot; the special card is outside the decks.", "",
             "`LordsCardManifestTests` compares the actual C# catalogs and excludes methods with Skip. "
             "`--results <TRX>` requires all referenced tests to pass. "
             "The generated table alone does not establish test execution or UI acceptance.", ""]
    for pack in sorted(packs, key=lambda p: p["id"]):
        number = pack["id"].rsplit("-", 1)[1]
        lines.extend([f"## {pack['id']}", "", f"[Logic and sources](T27-LORDS-{number}.md).", "",
                      "| Card | Event / reaction | Combat (initiative) | Behavioral tests |",
                      "| --- | --- | --- | --- |"])
        for card_id in pack["content_ids"]:
            card, source = cards[card_id], sources[card_id]
            event = f"`{card['programId']}`"
            if card["kind"] == "SpecialEvent":
                event = f"`{card['automaticEntry']}` → {event}"
            combat = ", ".join(f"`{program}` ({initiative})" for program, initiative in
                               zip(card["combatPrograms"], card["combatInitiatives"])) or "Not applicable"
            tests = "<br>".join(test_link(name) for name in card["tests"])
            lines.append(f"| `{card_id}` — {source['title']} | {event} | {combat} | {tests} |")
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--results", type=Path)
    args = parser.parse_args()
    sources, cards, packs = verified_cards()
    content = report(sources, cards, packs)
    if args.check:
        assert REPORT.exists() and REPORT.read_text(encoding="utf-8") == content, "Regenerate Lords card coverage report"
    else:
        REPORT.write_text(content, encoding="utf-8")
    if args.results:
        verify_results(args.results, cards)
    print("PASS: 14 Lords cards, three complete packs, matching rules and initiatives, current report")


if __name__ == "__main__":
    main()
